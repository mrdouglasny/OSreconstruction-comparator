#!/usr/bin/env python3
"""Generate a self-contained Solution.lean: the package's Definitions.lean, the three
bridge files and the package Solution.lean concatenated into ONE module, so that every
compared constant is elaborated locally on both sides of the Comparator run (an imported
module's auxiliary proofs are not re-exported identically under the module system).
Usage: gen_solution.py PACKAGE_COMPARATOR_DIR OUT"""
import sys,re,os
src,out=sys.argv[1],sys.argv[2]
order=['Definitions','WightmanBridge','OSBridge','ReverseBridge','Solution']
local=set(order)
imports=[]; bodies=[]
for m in order:
    s=open(os.path.join(src,m+'.lean'),encoding='utf-8').read()
    lines=s.split('\n')
    # header = up to and including the `@[expose] public section` line
    try: k=next(i for i,l in enumerate(lines) if l.strip()=='@[expose] public section')
    except StopIteration: raise SystemExit(f'{m}: no `@[expose] public section` header')
    for l in lines[:k]:
        mm=re.match(r'^(?:public )?import ([\w.]+)',l)
        if mm and mm.group(1) not in local and mm.group(1) not in imports: imports.append(mm.group(1))
    body='\n'.join(lines[k+1:]).strip('\n')
    bodies.append(f'/-! ### From the package file `verification/comparator/{m}.lean` -/\n\n'+body)
if '--import-all-mathlib' in sys.argv:
    imports=['Mathlib']+[i for i in imports if not i.startswith('Mathlib')]
hdr='''/-
Copyright (c) 2025 ModularPhysics Contributors. All rights reserved.
Released under Apache 2.0 license.
-/
module

'''+'\n'.join('public import '+i for i in imports)+'''

@[expose] public section

/-!
# Registry Solution

The package's Mathlib-only audit definitions, its three bridge files and its Solution,
concatenated into one module (generated by `scripts/gen_solution.py`). The compared
constants `OSReconstructionAudit.*` are therefore elaborated here, locally, from the same
text as in `RegistryChallenge.lean`; only the production proofs are imported.
-/

'''
open(out,'w',encoding='utf-8').write(hdr+'\n\n'.join(bodies)+'\n')
print('imports:',imports); print('lines:',hdr.count('\n')+sum(b.count('\n')+2 for b in bodies))
